/// Окно контекста для запросов к ИИ.
///
/// Раньше на каждое сообщение уходила ВСЯ переписка целиком. Это росло без
/// ограничений: после ~40–60 реплик запрос упирается в лимит контекста модели
/// (провайдер отвечает 400, а пользователь видит обычную «ошибку соединения»),
/// стоимость токенов растёт квадратично по длине диалога, а тело POST на
/// слабой сети перестаёт укладываться в sendTimeout.
///
/// Держим только хвост переписки. System-промпт добавляется вызывающим кодом
/// отдельно и в окно не входит — он нужен всегда.
const int kAiContextWindow = 20;

/// Максимальная длина одного сообщения в символах. Вставленный студентом
/// лог на 200 КБ иначе улетает в запрос целиком.
const int kAiMaxMessageChars = 8000;

/// Последние [kAiContextWindow] сообщений в формате API, с обрезкой слишком
/// длинных. Границу режем по началу сообщения, а не по середине пары
/// вопрос-ответ, — модель лучше держит диалог, когда он начинается с реплики
/// пользователя, но специально выравнивать не нужно: роли передаются явно.
List<Map<String, dynamic>> aiContextWindow(List<Map<String, String>> msgs) {
  final tail = msgs.length <= kAiContextWindow
      ? msgs
      : msgs.sublist(msgs.length - kAiContextWindow);

  return tail.map((m) {
    final text = m['text'] ?? '';
    return <String, dynamic>{
      'role': m['role'] ?? 'user',
      'content': text.length > kAiMaxMessageChars
          ? '${text.substring(0, kAiMaxMessageChars)}…'
          : text,
    };
  }).toList();
}
