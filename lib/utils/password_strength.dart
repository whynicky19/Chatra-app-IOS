/// Оценка надёжности пароля в баллах 0..100.
///
/// Раньше эта шкала жила приватным геттером `_pwScore` внутри
/// register_screen.dart, и шторка смены пароля не могла ей воспользоваться:
/// при регистрации пользователь видел индикатор надёжности, а при смене
/// пароля — нет, хотя требование к паролю то же самое.
///
/// Шкала намеренно грубая (5 шагов по 20): она отвечает на вопрос «этот
/// пароль вообще стоит ставить?», а не измеряет энтропию.
int passwordScore(String p) {
  if (p.isEmpty) return 0;
  var s = 0;
  if (p.length >= 6) s += 20;
  if (p.length >= 10) s += 20;
  if (RegExp(r'[A-Z]').hasMatch(p)) s += 20;
  if (RegExp(r'[0-9]').hasMatch(p)) s += 20;
  if (RegExp(r'[^A-Za-z0-9]').hasMatch(p)) s += 20;
  return s;
}
